create extension if not exists pgcrypto;

create table if not exists public.tracked_repos (
  id uuid primary key default gen_random_uuid(),
  repo_owner text not null,
  repo_name text not null,
  repo_url text generated always as ('https://github.com/' || repo_owner || '/' || repo_name) stored,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint tracked_repos_owner_name_unique unique (repo_owner, repo_name)
);

create table if not exists public.repo_daily_metrics (
  id bigint generated by default as identity primary key,
  tracked_repo_id uuid not null references public.tracked_repos(id) on delete cascade,
  collected_on date not null,
  stars integer not null check (stars >= 0),
  forks integer not null check (forks >= 0),
  raw_payload jsonb,
  created_at timestamptz not null default now(),
  constraint repo_daily_metrics_unique_snapshot unique (tracked_repo_id, collected_on)
);

create index if not exists repo_daily_metrics_repo_collected_idx
  on public.repo_daily_metrics (tracked_repo_id, collected_on desc);

create index if not exists repo_daily_metrics_collected_idx
  on public.repo_daily_metrics (collected_on desc);

create or replace view public.latest_repo_metrics as
select distinct on (m.tracked_repo_id)
  m.tracked_repo_id,
  r.repo_owner,
  r.repo_name,
  r.repo_url,
  m.stars,
  m.forks,
  m.collected_on
from public.repo_daily_metrics m
join public.tracked_repos r
  on r.id = m.tracked_repo_id
where r.is_active = true
order by m.tracked_repo_id, m.collected_on desc;

create or replace function public.cleanup_old_metrics()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_rows bigint;
begin
  delete from public.repo_daily_metrics
  where collected_on < (current_date - interval '3 months');

  get diagnostics deleted_rows = row_count;
  return deleted_rows;
end;
$$;

alter table public.tracked_repos enable row level security;
alter table public.repo_daily_metrics enable row level security;

drop policy if exists "Public read tracked repos" on public.tracked_repos;
create policy "Public read tracked repos"
  on public.tracked_repos
  for select
  using (true);

drop policy if exists "Public read repo metrics" on public.repo_daily_metrics;
create policy "Public read repo metrics"
  on public.repo_daily_metrics
  for select
  using (true);

grant usage on schema public to anon, authenticated;
grant select on public.tracked_repos to anon, authenticated;
grant select on public.repo_daily_metrics to anon, authenticated;
grant select on public.latest_repo_metrics to anon, authenticated;
grant execute on function public.cleanup_old_metrics() to service_role;
