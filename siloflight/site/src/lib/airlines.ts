export function airlineName(
  rawName: string | null,
  icao: string | null,
  iata: string | null,
): string | null {
  if (icao && ICAO_TO_NAME[icao.toUpperCase()]) {
    return ICAO_TO_NAME[icao.toUpperCase()];
  }
  if (iata && IATA_TO_NAME[iata.toUpperCase()]) {
    return IATA_TO_NAME[iata.toUpperCase()];
  }
  // Treat 3-letter all-caps as a likely ICAO code we don't have mapped — drop it.
  if (rawName && /^[A-Z]{3}$/.test(rawName) && iata) {
    return iata;
  }
  return rawName;
}
